/**
 * DocumentRetentionStatus - สถານะการทำลายเอกสารตามอายุ
 *
 * ใช้สำหรับกำหนดสถานะว่าเอกสารสามารถทำลายได้หรือไม่ ตามเกณฑ์อายุ 10 ปี
 */
export enum DocumentRetentionStatus {
  /**
   * เอกสารอายุไม่ถึง 10 ปี — ยังไม่สามารถทำลายได้
   */
  ACTIVE = 'ACTIVE',

  /**
   * เอกสารครบ 10 ปีแล้ว — สามารถทำลายได้
   */
  DESTROYABLE = 'DESTROYABLE',

  /**
   * เอกสารครบ 10 ปีแล้ว แต่ยังติดพันกับสัญญา — ทำลายไม่ได้
   */
  DESTROYABLE_HOLD = 'DESTROYABLE_HOLD',

  /**
   * เอกสารเกิน 10 ปีขึ้นไป — ทำลายทิ้งได้ (ถึงกำหนดทำลาย)
   */
  EXPIRED = 'EXPIRED',
}
